"""C-182 青花：古琴式的低音拨弦（阻尼大、余音短）和泛音（高八度、很轻），疏疏落落；瓶子转身时一阵很轻的气流声，转到背面落一个泛音。"""
from synth import string, bell, whoosh, filt, pad, hz


def score(m):
    d = m.dur + .5
    m.put(filt(pad([hz(38), hz(45)], d, 400, a=1.0, rel=1.5), "low", 500), 0, .18)
    for t0, n, g in ((.2, 45, .6), (.75, 52, .45), (1.25, 50, .5), (1.7, 57, .45), (2.2, 55, .45), (2.6, 50, .5)):
        m.put(string(m, hz(n), 2.0, .994, .25), t0, g, -.2)
    for t0, n in ((.95, 81), (1.95, 86), (2.85, 79)):
        m.put(bell(hz(n), 1.5, 2.0, .3), t0, .12, .3)
    m.put(whoosh(m, 1.1, 250, 1200), 2.85, .12)
    m.put(string(m, hz(38), 2.2, .995, .25), 3.9, .6)
    m.put(bell(hz(88), 1.6, 2.0, .3), 3.95, .14, .2)

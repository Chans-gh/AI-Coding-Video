"""C-102 颗粒渐变开场：从静里升起一层温暖的长音铺底，每穿过一层光就有一声轻柔的扫过声，带路的光球伴着几颗高处的铃音；最后一句话出来时一个大和弦慢慢展开。"""
from synth import pad, whoosh, bell, drone, riser, hz


def score(m):
    m.put(drone(hz(38), 5.0, .2), 0, .12)
    m.put(pad([hz(50), hz(57), hz(62), hz(66)], 3.6, 900, 1.2, 1.2), 0, .12)
    m.put(riser(m, 3.4), .2, .06)
    for k, tt_ in enumerate((.9, 1.5, 2.0, 2.45, 2.85, 3.2, 3.5)):
        m.put(whoosh(m, .5, 200, 2500 + 300 * k), tt_, .08)
    for tt_, n in ((.6, 74), (1.4, 78), (2.2, 81), (3.0, 86)):
        m.put(bell(hz(n), 1.4, 3.0, .8), tt_, .05)
    m.put(pad([hz(45), hz(52), hz(57), hz(61), hz(64)], 1.4, 1600, .5, .9), 3.6, .16)
    m.put(bell(hz(69), 1.4, 2.0, 1.0), 3.7, .08)
